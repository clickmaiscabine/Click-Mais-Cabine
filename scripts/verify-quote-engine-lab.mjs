import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const evidence=JSON.parse(read('docs/06_testes/BR002_TURNO2_EVIDENCIAS.json'));
const code=read('n8n/generated/quote-engine.generated.js');
const workflow=JSON.parse(read('n8n/workflows/f4/CM-WF-030.lab.json'));
assert.equal(workflow.active,false);
assert.equal(workflow.nodes.length,2);
assert.ok(workflow.nodes.every(n=>!n.credentials));
assert.equal(workflow.nodes.find(n=>n.type==='n8n-nodes-base.code').parameters.jsCode,code);
const run=new Function('$json',code);
for (const c of evidence.cases) assert.deepEqual(run(c.input).json,c.output,'LAB execution parity: '+c.case_id);
const [first,second,social,periods,dates,price]=evidence.cases.map(c=>c.output);
assert.deepEqual(first.quote_result.customerVisible,{pix:5129.1,card:6255});
assert.deepEqual([first.quote_result.corporate.sinal_50,first.quote_result.corporate.saldo_no_evento],[2564.55,2564.55]);
assert.deepEqual(second.quote_result.customerVisible,{pix:1951.6,card:2380});
assert.deepEqual(social.quote_result.customerVisible,{pix:1200,card:1420});
assert.equal(periods.status,'human_required');assert.equal(dates.status,'blocked');assert.equal(price.status,'human_required');
const legacy=new Function('$json',read('n8n/generated/f2-quote-kernel.generated.js'));
assert.deepEqual(social,legacy(evidence.cases[2].input).json);
if(evidence.kernel_sha256) assert.equal(createHash('sha256').update(code).digest('hex'),evidence.kernel_sha256);
console.log('LAB evidence verified: 6 cases; corporate acceptance, full social parity and blocking guards.');
